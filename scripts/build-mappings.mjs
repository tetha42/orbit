function main() {
	if (!fs.existsSync(MAP_FILE)) {
		console.error(`Map file not found: ${MAP_FILE}. Run ./scripts/scan.sh first.`);
		process.exit(1);
	}

	const data = JSON.parse(fs.readFileSync(MAP_FILE, 'utf8'));
	const definitions = data.definitions || [];

	let mappedCount = 0;
	let unmappedCount = 0;

	for (const item of definitions) {
		if (DICTIONARY[item.oldName]) {
			item.newName = DICTIONARY[item.oldName];
			mappedCount++;
		} else if (!item.newName) {
			unmappedCount++;
		}
	}

	fs.writeFileSync(MAP_FILE, JSON.stringify({ definitions }, null, 2) + '\n', 'utf8');
	console.log(`[Mapper] Mapped ${mappedCount} identifiers to English.`);
	console.log(`[Mapper] Remaining unmapped: ${unmappedCount}`);
}

main();
